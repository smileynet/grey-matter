#!/usr/bin/env node
// Tests for install-agents-md.mjs: size budget + managed-block safety. Every test uses throwaway
// --target files under the OS temp dir; no real harness file is touched.
//
// Run: node --test scripts/install-agents-md.test.mjs

import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { BUDGET_BYTES, OWNER_MARK, SOURCE, findBlock, revOf } from "./install-agents-md.mjs";

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), "install-agents-md.mjs");
const run = (...args) => spawnSync(process.execPath, [SCRIPT, ...args], { encoding: "utf8" });
const source = () => readFileSync(SOURCE, "utf8");

function withDir(fn) {
  const d = mkdtempSync(join(tmpdir(), "gm-agentsmd-"));
  try { fn(d); } finally { rmSync(d, { recursive: true, force: true }); }
}

test("source global/AGENTS.md is within the always-on size budget", () => {
  assert.ok(Buffer.byteLength(source()) <= BUDGET_BYTES);
});

test("install creates nested targets holding only the block; reinstall is a no-op", () => {
  withDir((d) => {
    const t = join(d, "a", "AGENTS.md");
    assert.equal(run("--target", t).status, 0);
    const text = readFileSync(t, "utf8");
    assert.equal(findBlock(text, "global").body, source());
    assert.ok(text.startsWith("<!-- grey-matter:begin global rev="));
    assert.match(run("--target", t).stdout, /current/);
  });
});

test("install appends to a foreign file; user text survives install, update and uninstall", () => {
  withDir((d) => {
    const t = join(d, "CLAUDE.md");
    writeFileSync(t, "my own rules\n");
    const r = run("--target", t);
    assert.equal(r.status, 0, r.stdout + r.stderr);
    assert.match(r.stdout, /append/);
    assert.ok(readFileSync(t, "utf8").startsWith("my own rules\n"));
    // An outdated block is replaced in place; text on both sides is left alone.
    const text = readFileSync(t, "utf8"), b = findBlock(text, "global");
    const stale = "- an old rule\n";
    const staleBlock = text.slice(b.start, b.end).replace(source(), stale).replace(/rev=[0-9a-f]+/, `rev=${revOf(stale)}`);
    writeFileSync(t, text.slice(0, b.start) + staleBlock + "trailing user note\n");
    assert.match(run("--target", t).stdout, /update/);
    const updated = readFileSync(t, "utf8");
    assert.ok(updated.startsWith("my own rules\n") && updated.endsWith("trailing user note\n"));
    assert.equal(findBlock(updated, "global").body, source());
    assert.equal(run("uninstall", "--target", t).status, 0);
    assert.equal(readFileSync(t, "utf8"), "my own rules\ntrailing user note\n");
  });
});

test("an edited block is refused as drift with a diff; --force overwrites only the block", () => {
  withDir((d) => {
    const t = join(d, "AGENTS.md");
    writeFileSync(t, "keep me\n");
    run("--target", t);
    const edited = readFileSync(t, "utf8").replace("Minimal code:", "Mostly minimal code:");
    writeFileSync(t, edited);
    const r = run("--target", t);
    assert.notEqual(r.status, 0);
    assert.match(r.stdout, /refused .*edited/);
    assert.match(r.stdout, /\+ - Mostly minimal code:/);
    assert.equal(readFileSync(t, "utf8"), edited);
    assert.notEqual(run("uninstall", "--target", t).status, 0);
    assert.equal(run("--target", t, "--force").status, 0);
    const forced = readFileSync(t, "utf8");
    assert.ok(forced.startsWith("keep me\n"));
    assert.equal(findBlock(forced, "global").body, source());
  });
});

test("a generated file is refused, not appended to, unless --force", () => {
  withDir((d) => {
    const t = join(d, "AGENTS.md");
    const generated = "# crew-research steering (full tier)\n# Auto-generated by crew-research init.sh — do not edit manually\n";
    writeFileSync(t, generated);
    const r = run("--target", t);
    assert.notEqual(r.status, 0);
    assert.match(r.stdout, /refused .*generated/);
    assert.equal(readFileSync(t, "utf8"), generated);
    assert.equal(run("--target", t, "--force").status, 0);
    assert.ok(readFileSync(t, "utf8").startsWith(generated));
  });
});

test("a whole-file install with the old owner mark migrates to a block", () => {
  withDir((d) => {
    const t = join(d, "AGENTS.md");
    writeFileSync(t, `${OWNER_MARK}\n- an old rule\n`);
    assert.match(run("list", "--target", t).stdout, /legacy/);
    assert.match(run("--target", t).stdout, /migrate/);
    const text = readFileSync(t, "utf8"), b = findBlock(text, "global");
    assert.equal(b.body, source());
    assert.equal(text.length, b.end - b.start, "the old whole-file copy is replaced by the block alone");
  });
});

test("dry-run writes nothing and prints the diff", () => {
  withDir((d) => {
    const t = join(d, "AGENTS.md");
    const r = run("--target", t, "--dry-run");
    assert.equal(r.status, 0);
    assert.match(r.stdout, /\+ - Minimal code:/);
    assert.ok(!existsSync(t));
  });
});

test("uninstall removes a file left empty, never a foreign one", () => {
  withDir((d) => {
    const mine = join(d, "mine.md"), theirs = join(d, "theirs.md");
    run("--target", mine);
    writeFileSync(theirs, "foreign\n");
    assert.equal(run("uninstall", "--target", mine, "--target", theirs).status, 0);
    assert.ok(!existsSync(mine));
    assert.equal(readFileSync(theirs, "utf8"), "foreign\n");
    assert.match(run("list", "--target", theirs).stdout, /foreign/);
  });
});

test("--name and --source install a separate block beside the global one", () => {
  withDir((d) => {
    const t = join(d, "AGENTS.md"), pointer = join(d, "pointer.md");
    writeFileSync(pointer, "See docs/agents/ for grey-matter conventions.\n");
    run("--target", t);
    assert.equal(run("--name", "pointer", "--source", pointer, "--target", t).status, 0);
    const text = readFileSync(t, "utf8");
    assert.equal(findBlock(text, "global").body, source());
    assert.equal(findBlock(text, "pointer").body, readFileSync(pointer, "utf8"));
    assert.notEqual(run("--name", "pointer", "--source", pointer).status, 0, "a named block needs explicit targets");
  });
});

test("the default codex target follows CODEX_HOME", () => {
  withDir((d) => {
    const home = join(d, "home"), codexHome = join(d, "custom-codex");
    mkdirSync(home); mkdirSync(codexHome);
    const r = spawnSync(process.execPath, [SCRIPT], { encoding: "utf8", env: { ...process.env, HOME: home, USERPROFILE: home, CODEX_HOME: codexHome } });
    assert.equal(r.status, 0, r.stdout + r.stderr);
    assert.equal(findBlock(readFileSync(join(codexHome, "AGENTS.md"), "utf8"), "global").body, source());
    assert.equal(existsSync(join(home, ".codex", "AGENTS.md")), false);
  });
});
