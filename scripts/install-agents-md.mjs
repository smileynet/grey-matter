#!/usr/bin/env node
// install-agents-md.mjs: install grey-matter's user-level AGENTS.md (global/AGENTS.md) into
// each harness's global instructions file, as a managed block. Sibling of deploy.mjs; same
// safety contract.
//
// Usage:
//   node scripts/install-agents-md.mjs [install] [--dry-run] [--force] [--target <file> ...]
//   node scripts/install-agents-md.mjs list|uninstall [--dry-run] [--force] [--target <file> ...]
//   ... --name <block> --source <file> --target <file>   (another block, e.g. a repo pointer)
//
// Targets (default: each one whose harness dir exists on this machine):
//   kiro-cli    ~/.kiro/steering/AGENTS.md   (Kiro loads AGENTS.md there, always-on)
//   codex       $CODEX_HOME/AGENTS.md (default ~/.codex/AGENTS.md)
//   claude      ~/.claude/CLAUDE.md
//   opencode    ~/.config/opencode/AGENTS.md
// --target replaces the whole set (used by tests; never touches real files then).
//
// Ownership: grey-matter owns only the text between its begin/end markers, so a user's own
// rules can share the file. The begin marker records a hash of the body as installed; a body
// that no longer matches was edited by hand, and install/uninstall refuse it (drift) unless
// --force. A file another tool generates is not appended to, since the generator would
// overwrite the block. A whole file installed with the old OWNER_MARK migrates to a block.
// Size budget: the block body must stay <= BUDGET_BYTES, because every harness pays for it on
// every turn. Install refuses to run over budget.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, realpathSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE = join(REPO, "global", "AGENTS.md");
export const BUDGET_BYTES = 3072;
export const OWNER_MARK = "<!-- installed by grey-matter (global/AGENTS.md): edit the source, then reinstall -->";
export const GENERATED = /auto-generated by|do not edit/i;

const H = homedir();
// Same resolution as deploy.mjs, so global rules land beside the skills Codex loads.
const CODEX = process.env.CODEX_HOME || join(H, ".codex");
export const KNOWN = [
  { harness: "kiro-cli", dir: join(H, ".kiro"), file: join(H, ".kiro", "steering", "AGENTS.md") },
  { harness: "codex", dir: CODEX, file: join(CODEX, "AGENTS.md") },
  { harness: "claude", dir: join(H, ".claude"), file: join(H, ".claude", "CLAUDE.md") },
  { harness: "opencode", dir: join(H, ".config", "opencode"), file: join(H, ".config", "opencode", "AGENTS.md") },
];

export const revOf = (body) => createHash("sha256").update(body).digest("hex").slice(0, 7);
const blockOf = (name, body) => `<!-- grey-matter:begin ${name} rev=${revOf(body)} -->\n${body}<!-- grey-matter:end ${name} -->\n`;

export function findBlock(text, name) {
  const m = new RegExp(`<!-- grey-matter:begin ${name} rev=([0-9a-f]+) -->\\n([\\s\\S]*?)<!-- grey-matter:end ${name} -->\\n?`).exec(text);
  return m && { start: m.index, end: m.index + m[0].length, rev: m[1], body: m[2], drifted: revOf(m[2]) !== m[1] };
}

function parseArgs(argv) {
  const a = { cmd: "install", dryRun: false, force: false, targets: [], name: "global", source: SOURCE };
  for (let i = 0; i < argv.length; i++) {
    const x = argv[i];
    if (["install", "list", "uninstall"].includes(x)) a.cmd = x;
    else if (x === "--dry-run") a.dryRun = true;
    else if (x === "--force") a.force = true;
    else if (x === "--target" && argv[i + 1]) a.targets.push(resolve(argv[++i]));
    else if (x === "--source" && argv[i + 1]) a.source = resolve(argv[++i]);
    else if (x === "--name" && /^[a-z][a-z0-9-]*$/.test(argv[i + 1] ?? "")) a.name = argv[++i];
    else { console.error(`unknown argument: ${x}`); process.exit(2); }
  }
  if (!a.targets.length && a.name !== "global") { console.error(`--name ${a.name} needs --target`); process.exit(2); }
  if (!a.targets.length) a.targets = KNOWN.filter((k) => existsSync(k.dir)).map((k) => k.file);
  return a;
}

// Line-set diff: enough to show what an install changes or what a hand edit added.
function diff(from, to) {
  const A = from.split("\n"), B = to.split("\n");
  return [...A.filter((l) => l && !B.includes(l)).map((l) => `      - ${l}`), ...B.filter((l) => l && !A.includes(l)).map((l) => `      + ${l}`)].join("\n");
}

function state(file, name) {
  if (!existsSync(file)) return { kind: "absent" };
  const text = readFileSync(file, "utf8"), block = findBlock(text, name);
  if (block) return { kind: block.drifted ? "drifted" : "installed", text, block };
  if (name === "global" && text.startsWith(OWNER_MARK)) return { kind: "legacy", text };
  return { kind: GENERATED.test(text.split("\n", 5).join("\n")) ? "generated" : "foreign", text };
}

function install({ dryRun, force, targets, name, source }) {
  const body = readFileSync(source, "utf8");
  const size = Buffer.byteLength(body);
  if (size > BUDGET_BYTES) {
    console.error(`${source} is ${size} B, over the ${BUDGET_BYTES} B budget; trim it before installing.`);
    process.exit(1);
  }
  const want = blockOf(name, body);
  let refused = 0;
  for (const file of targets) {
    const s = state(file, name);
    let action, next, why = "", shown = "";
    if (s.kind === "absent") { action = "create"; next = want; shown = diff("", body); }
    else if (s.kind === "legacy") { action = "migrate"; next = want; }
    else if ((s.kind === "drifted" || s.kind === "generated") && !force) {
      action = "refused";
      why = s.kind === "drifted" ? " (block edited since install; move the edit into the source, or --force)" : " (generated by another tool, which would overwrite the block; --force to append anyway)";
      if (s.kind === "drifted") shown = diff(body, s.block.body);
    } else if (s.block) {
      action = s.block.body === body && !s.block.drifted ? "current" : "update";
      next = s.text.slice(0, s.block.start) + want + s.text.slice(s.block.end);
      shown = diff(s.block.body, body);
    } else { action = "append"; next = s.text.trim() ? s.text.replace(/\n*$/, "\n\n") + want : want; shown = diff("", body); }
    if (action === "refused") refused++;
    console.log(`  ${action.padEnd(8)} ${file}${why}`);
    if (shown && (dryRun || action === "refused")) console.log(shown);
    if (dryRun || !next || action === "current") continue;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, next);
  }
  console.log(`${dryRun ? "(dry-run) " : ""}${size} B ${name} block, ${targets.length - refused}/${targets.length} targets ok`);
  if (refused) process.exitCode = 1;
}

function list({ targets, name }) {
  for (const file of targets) console.log(`  ${state(file, name).kind.padEnd(9)} ${file}`);
}

function uninstall({ dryRun, force, targets, name }) {
  for (const file of targets) {
    const s = state(file, name);
    if (s.kind === "drifted" && !force) { console.log(`  refused  ${file} (block edited since install; --force removes it anyway)`); process.exitCode = 1; continue; }
    if (!s.block && s.kind !== "legacy") { console.log(`  skip     ${file} (${s.kind})`); continue; }
    const before = s.block ? s.text.slice(0, s.block.start).replace(/\n\n$/, "\n") : "";
    const rest = s.block ? before + s.text.slice(s.block.end) : "";
    console.log(`  ${rest.trim() ? "unblock " : "remove  "} ${file}`);
    if (dryRun) continue;
    if (rest.trim()) writeFileSync(file, rest);
    else rmSync(file);
  }
}

if (process.argv[1] && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(resolve(process.argv[1]))) {
  const a = parseArgs(process.argv.slice(2));
  ({ install, list, uninstall })[a.cmd](a);
}
