#!/usr/bin/env node
// Tests for check-guidance.mjs. Fixtures rebuild what the 2026-10-27 randomserver cutover found
// by hand (a `recall` command after the binary was removed, a steering symlink to a deleted
// file, crew's generated steering) inside a throwaway HOME and repo.
//
// Run: node --test scripts/check-guidance.test.mjs

import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const HERE = dirname(fileURLToPath(import.meta.url));
const SCRIPT = join(HERE, "check-guidance.mjs");
const INSTALL = join(HERE, "install-agents-md.mjs");
const PAIRS = join(HERE, "..", "global", "conflict-pairs.json");

function fixture(fn) {
  const d = mkdtempSync(join(tmpdir(), "gm-guidance-"));
  const home = join(d, "home"), repo = join(d, "repo");
  const env = { ...process.env, HOME: home, USERPROFILE: home, CODEX_HOME: "", PATH: dirname(process.execPath) };
  const put = (path, text) => { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text); };
  try { fn({ home, repo, env, put, run: (...args) => spawnSync(process.execPath, [SCRIPT, "--repo", repo, ...args], { encoding: "utf8", env }) }); }
  finally { rmSync(d, { recursive: true, force: true }); }
}

function cutover({ home, repo, env, put }) {
  mkdirSync(join(home, ".claude"), { recursive: true });
  spawnSync(process.execPath, [INSTALL, "--target", join(home, ".claude", "CLAUDE.md")], { env });
  put(join(home, ".claude", "skills", "tdd", "SKILL.md"), "---\nname: tdd\n---\n");
  put(join(home, ".kiro", "steering", "crew.md"), "# crew-research steering (full tier)\n# Auto-generated by crew-research init.sh — do not edit manually\n");
  symlinkSync(join(home, "code", "tkt", "steering", "frontier-work.md"), join(home, ".kiro", "steering", "frontier-work.md"));
  put(join(repo, "docs", "here.md"), "present\n");
  put(join(repo, "mise.toml"), "[tasks.test]\nrun = \"node --test\"\n");
  put(join(repo, "AGENTS.md"), [
    "# Agents",
    "- `recall search <topic>` finds earlier notes.",
    "- `node --test` runs the suite; `mise run test` does the same.",
    "- `mise run build` builds it.",
    "- Read [the spec](docs/missing.md) and [this](docs/here.md).",
    "- Use the `wayfinder` skill for foggy work, the `tdd` skill for slices, and `/grey-matter:tdd` by name.",
    "- Observed beats documented: running code, real output, and actual bytes outrank specs, docs, and commentary. When they disagree, trust the observation, flag the gap, and say what you verified vs inferred. Absence from a listing or doc is not absence.",
    "- Skip the tests for doc-only changes.",
    "<!-- overrides: minimal-code -->",
    "- Log on entry and exit in the request handlers; the auditors require it.",
    "",
    "```bash",
    "cd ~/code/notes && recall import .memory/",
    "```",
    "",
  ].join("\n"));
}

const parse = (r) => JSON.parse(r.stdout).findings;
const has = (findings, tier, rule, re) => findings.some((f) => f.tier === tier && f.rule === rule && re.test(`${f.file}:${f.line} ${f.message}`));

test("the cutover fixtures are reported: dead command, dead skill, dead steering symlink, generator header", () => {
  fixture((f) => {
    cutover(f);
    const r = f.run("--json");
    assert.equal(r.status, 1, r.stderr);
    const found = parse(r);
    assert.ok(has(found, "error", "dead-command", /AGENTS\.md:2 .*recall/), "inline recall");
    assert.ok(has(found, "error", "dead-command", /AGENTS\.md:13 .*recall/), "recall in a shell fence");
    assert.ok(has(found, "error", "dead-skill", /AGENTS\.md:6 .*wayfinder/));
    assert.ok(has(found, "error", "dead-link", /frontier-work\.md/));
    assert.ok(has(found, "error", "generator", /crew\.md:2/));
    assert.ok(has(found, "error", "dead-path", /AGENTS\.md:5 .*docs\/missing\.md/));
    assert.ok(has(found, "error", "dead-command", /AGENTS\.md:4 .*mise run build/), "missing mise task");
    assert.ok(has(found, "error", "duplicate", /AGENTS\.md:7 .*CLAUDE\.md/));
    assert.deepEqual(found.filter((x) => x.tier === "error" && x.line === 3), [], "node and a defined mise task are live");
    assert.deepEqual(found.filter((x) => x.rule === "dead-skill").map((x) => x.message.match(/`([^`]+)`/)[1]), ["wayfinder"]);
    assert.ok(!found.some((x) => x.rule === "dead-path" && /here\.md/.test(x.message)));
    assert.ok(!found.some((x) => x.rule === "dead-command" && /`cd`/.test(x.message)));
  });
});

test("judgment findings are reported, overrides listed as info, and nothing is edited", () => {
  fixture((f) => {
    cutover(f);
    const snapshot = (dir) => readdirSync(dir, { recursive: true }).filter((p) => !statSync(join(dir, p), { throwIfNoEntry: false })?.isDirectory()).map((p) => [p, readFileSync(join(dir, p), "utf8")]);
    const before = JSON.stringify([snapshot(f.repo), snapshot(join(f.home, ".claude"))]);
    const found = parse(f.run("--json"));
    assert.ok(has(found, "judgment", "contradiction", /AGENTS\.md:8 .*done-evidenced/));
    assert.ok(has(found, "info", "override", /AGENTS\.md:10 .*minimal-code/));
    assert.equal(JSON.stringify([snapshot(f.repo), snapshot(join(f.home, ".claude"))]), before);
    assert.match(f.run().stdout, /known pairs/);
  });
});

test("a file referenced by guidance and changed after the guidance's last commit is flagged re-read", () => {
  fixture((f) => {
    f.put(join(f.repo, "AGENTS.md"), "- Deploy with `scripts/run.sh`.\n");
    f.put(join(f.repo, "scripts", "run.sh"), "echo v1\n");
    const git = (args, date) => spawnSync("git", ["-C", f.repo, "-c", "user.name=t", "-c", "user.email=t@t", ...args], { env: { ...f.env, PATH: process.env.PATH, GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date } });
    git(["init", "-q"]);
    git(["add", "."]); git(["commit", "-qm", "one"], "2026-01-01T00:00:00Z");
    writeFileSync(join(f.repo, "scripts", "run.sh"), "echo v2\n");
    git(["commit", "-qam", "two"], "2026-02-01T00:00:00Z");
    const r = spawnSync(process.execPath, [SCRIPT, "--repo", f.repo, "--json", "--no-global"], { encoding: "utf8", env: { ...f.env, PATH: process.env.PATH } });
    const found = parse(r);
    assert.ok(has(found, "judgment", "re-read", /AGENTS\.md:1 .*scripts[\\/]run\.sh/), JSON.stringify(found));
  });
});

test("size budgets: a file over --max-bytes is reported", () => {
  fixture((f) => {
    f.put(join(f.repo, "AGENTS.md"), `${"- a rule that says something.\n".repeat(20)}`);
    const found = parse(f.run("--json", "--no-global", "--max-bytes", "200"));
    assert.ok(has(found, "error", "budget", /AGENTS\.md/));
  });
});

test("clean guidance passes", () => {
  fixture((f) => {
    f.put(join(f.repo, "AGENTS.md"), "# Agents\n\n- Run `node --test` before closing a ticket.\n");
    const r = f.run();
    assert.equal(r.status, 0, r.stdout + r.stderr);
  });
});

test("conflict-pairs.json: unique kebab ids, both sides compile", () => {
  const { pairs } = JSON.parse(readFileSync(PAIRS, "utf8"));
  assert.ok(pairs.length > 0);
  assert.equal(new Set(pairs.map((p) => p.id)).size, pairs.length);
  for (const p of pairs) {
    assert.match(p.id, /^[a-z][a-z0-9-]*$/);
    new RegExp(p.a, "i"); new RegExp(p.b, "i");
  }
});
