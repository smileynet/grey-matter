#!/usr/bin/env node
// Tests for uninstall-crew-research.mjs against a throwaway fake home. Never touches ~.
// Run: node --test scripts/uninstall-crew-research.test.mjs

import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync, spawnSync } from "node:child_process";

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), "uninstall-crew-research.mjs");

function fakeHome() {
  const h = mkdtempSync(join(tmpdir(), "gm-crew-home-"));
  const put = (p, body = "x\n") => { mkdirSync(dirname(join(h, p)), { recursive: true }); writeFileSync(join(h, p), body); };
  // crew-deployed skills (listed) and foreign skills (not listed)
  for (const s of ["handoff", "code-review", "recall"]) put(`.kiro/skills/${s}/SKILL.md`);
  for (const s of ["archwright-survey", "brazil", "tkt"]) put(`.kiro/skills/${s}/SKILL.md`);
  put(".kiro/.crew-skills", "handoff\ncode-review\nrecall\nnot-present\n../escape\n");
  put(".kiro/.crew-tier", "full\n");
  for (const s of ["handoff", "grill-with-docs"]) put(`.agents/skills/${s}/SKILL.md`);
  put(".agents/skills/agy-own/SKILL.md");
  put(".agents/skills/.crew-skills-codex", "handoff\ngrill-with-docs\n");
  put(".agents/skills/.crew-skills-crush", "handoff\n");
  // steering: crew files, a symlinked crew-named file, foreign subdirs and files
  put(".kiro/steering/verification-protocol.md");
  put(".kiro/steering/source-authority.md");
  put(".kiro/steering/amazon-builder/amazon-builder-brazil.md");
  put(".kiro/steering/references/environment-gotchas.md");
  put(".kiro/steering/my-own-rule.md");
  put("elsewhere/image-handling.md");
  symlinkSync(join(h, "elsewhere/image-handling.md"), join(h, ".kiro/steering/image-handling.md"));
  put(".codex/AGENTS.md", "# crew-research steering (full tier)\n# Auto-generated by crew-research init.sh\n");
  return h;
}
const run = (h, ...a) => spawnSync(process.execPath, [SCRIPT, "--home", h, ...a], { encoding: "utf8" });
const has = (h, p) => existsSync(join(h, p));

test("dry-run removes nothing", () => {
  const h = fakeHome();
  try {
    const r = run(h);
    assert.equal(r.status, 0, r.stdout + r.stderr);
    assert.match(r.stdout, /remove .kiro\/skills\/handoff/);
    assert.ok(has(h, ".kiro/skills/handoff") && has(h, ".codex/AGENTS.md"));
  } finally { rmSync(h, { recursive: true, force: true }); }
});

test("apply removes exactly the manifest-named and crew-owned items, and snapshots first", () => {
  const h = fakeHome();
  try {
    const backup = join(h, "snap.tar.gz");
    const r = run(h, "--apply", "--backup", backup);
    assert.equal(r.status, 0, r.stdout + r.stderr);
    assert.ok(existsSync(backup));
    const entries = execFileSync("tar", ["-tzf", "snap.tar.gz"], { cwd: h, encoding: "utf8" });
    assert.match(entries, /\.kiro\/skills\/handoff\/SKILL.md/);
    assert.match(entries, /\.kiro\/steering\/image-handling.md/);
    for (const gone of [".kiro/skills/handoff", ".kiro/skills/code-review", ".kiro/skills/recall",
      ".agents/skills/handoff", ".agents/skills/grill-with-docs", ".kiro/.crew-skills", ".kiro/.crew-tier",
      ".agents/skills/.crew-skills-codex", ".kiro/steering/verification-protocol.md",
      ".kiro/steering/source-authority.md", ".codex/AGENTS.md"]) assert.ok(!has(h, gone), gone);
    // the do-not-touch set
    assert.deepEqual(readdirSync(join(h, ".kiro/skills")).sort(), ["archwright-survey", "brazil", "tkt"]);
    assert.deepEqual(readdirSync(join(h, ".agents/skills")), ["agy-own"]);
    for (const kept of [".kiro/steering/amazon-builder/amazon-builder-brazil.md",
      ".kiro/steering/references/environment-gotchas.md", ".kiro/steering/my-own-rule.md",
      ".kiro/steering/image-handling.md", "elsewhere/image-handling.md", "escape"]) {
      if (kept !== "escape") assert.ok(has(h, kept), kept);
    }
  } finally { rmSync(h, { recursive: true, force: true }); }
});

test("a grey-matter-owned dir and a non-crew codex AGENTS.md are kept", () => {
  const h = fakeHome();
  try {
    writeFileSync(join(h, ".kiro/skills/.installed-by-grey-matter.json"), JSON.stringify({ installed: ["code-review"] }));
    writeFileSync(join(h, ".codex/AGENTS.md"), "<!-- installed by grey-matter -->\n");
    const r = run(h, "--apply", "--backup", join(h, "s.tgz"));
    assert.equal(r.status, 0, r.stdout + r.stderr);
    assert.ok(has(h, ".kiro/skills/code-review"));
    assert.ok(has(h, ".codex/AGENTS.md"));
    assert.match(r.stdout, /owned by grey-matter/);
  } finally { rmSync(h, { recursive: true, force: true }); }
});
